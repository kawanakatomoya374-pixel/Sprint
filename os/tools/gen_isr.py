#!/usr/bin/env python3
"""Regenerates os/kernel/isr_stubs.S (the 256 interrupt entry stubs)."""
err_vecs = {8, 10, 11, 12, 13, 14, 17, 21, 29, 30}
out = ["/* generated by os/tools/gen_isr.py: 256 interrupt entry stubs; the vector (and a dummy error code) is pushed, then isr_common */",
       "    .section .text"]
for n in range(256):
    out += ["    .global isr_%d" % n, "    .align 8", "isr_%d:" % n]
    if n not in err_vecs:
        out.append("    pushq $0")
    out += ["    pushq $%d" % n, "    jmp isr_common"]
out += ["    .section .rodata", "    .align 8", "    .global isr_table", "isr_table:"]
out += ["    .quad isr_%d" % n for n in range(256)]
out.append('    .section .note.GNU-stack, "", @progbits')
open("os/kernel/isr_stubs.S", "w").write("\n".join(out) + "\n")
