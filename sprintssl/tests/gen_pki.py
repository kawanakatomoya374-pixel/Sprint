#!/usr/bin/env python3
"""Regenerates the test certificates in tests/data (needs the `cryptography` package). Chains A, B and C are for the X.509 and loopback tests; the interop/
folder holds servers with their private keys (EC P-256 under an intermediate, RSA 2048, Ed25519) that python's ssl module serves in the QEMU network test."""
import datetime, ipaddress, os
from cryptography import x509
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives.asymmetric import ed25519, ec, rsa
from cryptography.hazmat.primitives import hashes, serialization as S
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
NB, NA = datetime.datetime(2024, 1, 1), datetime.datetime(2049, 1, 1)
def name(cn): return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
def mk(key, subject, ikey, issuer, ca=False, path=None, sans=None, algo=None):
    b = (x509.CertificateBuilder().subject_name(name(subject)).issuer_name(name(issuer)).public_key(key.public_key()).serial_number(x509.random_serial_number())
         .not_valid_before(NB).not_valid_after(NA).add_extension(x509.BasicConstraints(ca=ca, path_length=path), critical=True))
    if sans:
        b = b.add_extension(x509.SubjectAlternativeName([x509.IPAddress(ipaddress.ip_address(s)) if s[0].isdigit() else x509.DNSName(s) for s in sans]), critical=False)
    return b.sign(ikey, algo)
pem = lambda c: c.public_bytes(S.Encoding.PEM)
keypem = lambda k: k.private_bytes(S.Encoding.PEM, S.PrivateFormat.PKCS8, S.NoEncryption())
def w(name, data):
    p = os.path.join(HERE, name); os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "wb").write(data)
SANS = ["interop.test", "localhost", "10.0.2.2"]
rk = ec.generate_private_key(ec.SECP256R1()); root = mk(rk, "Interop Root", rk, "Interop Root", True, None, None, hashes.SHA256())
w("interop/root.pem", pem(root))
ik = ec.generate_private_key(ec.SECP384R1()); inter = mk(ik, "Interop Intermediate", rk, "Interop Root", True, 0, None, hashes.SHA256())
lk = ec.generate_private_key(ec.SECP256R1()); leaf = mk(lk, "ec.interop.test", ik, "Interop Intermediate", False, None, SANS, hashes.SHA384())
w("interop/ec.pem", pem(leaf) + pem(inter)); w("interop/ec.key", keypem(lk))
rl = rsa.generate_private_key(65537, 2048); leaf = mk(rl, "rsa.interop.test", rk, "Interop Root", False, None, SANS, hashes.SHA256())
w("interop/rsa.pem", pem(leaf)); w("interop/rsa.key", keypem(rl))
el = ed25519.Ed25519PrivateKey.generate(); leaf = mk(el, "ed.interop.test", rk, "Interop Root", False, None, SANS, hashes.SHA256())
w("interop/ed.pem", pem(leaf)); w("interop/ed.key", keypem(el))
# another root, to be used as the wrong trust anchor
ok_ = ec.generate_private_key(ec.SECP256R1()); w("interop/other_root.pem", pem(mk(ok_, "Other Root", ok_, "Other Root", True, None, None, hashes.SHA256())))
# the roots as Sprint source for the SprintOS network test (os/user/testroots.sp)
def text(name): return open(os.path.join(HERE, "interop", name)).read()
src = "# generated by sprintssl/tests/gen_pki.py: the roots the QEMU network test trusts (and one it does not)\nexport const INTEROP_ROOT = \"\"\"" + text("root.pem") + "\"\"\"\nexport const OTHER_ROOT = \"\"\"" + text("other_root.pem") + "\"\"\"\n"
src += "export const ISRG_ROOT_X1 = \"\"\"" + text("isrg_root_x1.pem") + "\"\"\"\n"     # a real root (copied from the system store): GitHub Pages chains to it
open(os.path.join(HERE, "..", "..", "..", "os", "user", "testroots.sp"), "w").write(src)
