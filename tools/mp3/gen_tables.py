#!/usr/bin/env python3
"""Extract the numeric tables of minimp3 (CC0) into stdlib/mp3tab.sp.
usage: gen_tables.py minimp3.h > stdlib/mp3tab.sp && sprint fmt -w stdlib/mp3tab.sp"""
import re, sys
src = open(sys.argv[1]).read()

def grab(name, start=0):
    m = re.search(r'(?:static\s+)?(?:const\s+)?[\w ]*?\b' + re.escape(name) + r'\s*(?:\[[^\]]*\])+\s*=\s*\{', src[start:])
    i = start + m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                return src[i:j+1]
    raise SystemExit("unterminated " + name)

def flat(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    toks = re.findall(r'-?\d+\.?\d*(?:e-?\d+)?f?', body)
    return [t.rstrip('f') if '.' in t or 'e' in t else t for t in toks]

def emit(name, vals, per=16):
    print("export let %s = [" % name)
    for k in range(0, len(vals), per):
        print("    " + ", ".join(vals[k:k+per]) + ("," if k + per < len(vals) else ""))
    print("]\n")

print("# mp3tab: constant tables for sprintmp3 (generated by tools/mp3/gen_tables.py from minimp3, CC0). Do not edit.")
start = src.index('static void L3_huffman')
for n in ['g_scf_long','g_scf_short','g_scf_mixed','g_scf_partitions','g_scfc_decode','g_mod','g_preamp','g_pow43','g_aa','g_twid9','g_twid3','g_mdct_window','g_sec','g_win','g_expfrac','g_pan','halfrate']:
    pass
def rows(name):
    body = grab(name)
    rs = re.findall(r'\{([^{}]*)\}', body[1:])
    print("export let %s = [" % name)
    for k, r in enumerate(rs):
        print("    [" + ", ".join(flat(r)) + "]" + ("," if k + 1 < len(rs) else ""))
    print("]\n")
def one(name, per=16, start=0):
    emit(name, flat(grab(name, start)), per)
rows('g_scf_long'); rows('g_scf_short'); rows('g_scf_mixed')
rows('g_scf_partitions'); one('g_scfc_decode'); one('g_mod', 24); one('g_preamp')
one('g_pow43'); one('g_aa', 8); one('g_twid9', 9); one('g_twid3'); one('g_mdct_window', 18)
one('g_sec', 12); one('g_win', 16); one('g_expfrac'); one('g_pan', 2)
one('halfrate', 15)
one('tabs', 16, start); one('tab32', 16, start); one('tab33', 16, start); one('tabindex', 16, start); one('g_linbits', 16, start)
