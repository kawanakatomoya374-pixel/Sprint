/* jitgen: turns the relocatable object assembled from src/runtime/jit/stencils.S into src/runtime/jit/stencils.h.
 *
 * Every `.text.<name>` section is one stencil. Its bytes are copied verbatim; every relocation against one of the
 * hole symbols H0..H5, HQ/HQ2, HB0..HB5, JIT_T and JIT_X become patch records containing the offset, hole,
 * relocation width/kind and addend. The JIT only has to memcpy a stencil and write the holes. Usage:
 * jitgen stencils.o > stencils.h   (see `make jit-regen`) */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct { uint8_t ident[16]; uint16_t type, machine; uint32_t version; uint64_t entry, phoff, shoff; uint32_t flags;
                 uint16_t ehsize, phentsize, phnum, shentsize, shnum, shstrndx; } Ehdr;
typedef struct { uint32_t name, type; uint64_t flags, addr, offset, size; uint32_t link, info; uint64_t addralign, entsize; } Shdr;
typedef struct { uint32_t name; uint8_t info, other; uint16_t shndx; uint64_t value, size; } Sym;
typedef struct { uint64_t offset, info; int64_t addend; } Rela;

static unsigned char *img;
static size_t imglen;

static const char *hole_names[] = {
    "H0", "H1", "H2", "H3", "H4", "H5", "HQ", "JIT_T", "JIT_X", "HQ2",
    "HB0", "HB1", "HB2", "HB3", "HB4", "HB5"
};

static int hole_id(const char *s) {
    for (int i = 0; i < (int)(sizeof hole_names / sizeof hole_names[0]); i++) if (strcmp(s, hole_names[i]) == 0) return i;
    fprintf(stderr, "jitgen: unknown symbol '%s'\n", s);
    exit(1);
}

int main(int argc, char **argv) {
    if (argc != 2 && argc != 3) { fprintf(stderr, "usage: jitgen stencils.o [master-stencils.h] > stencils.h\n"); return 2; }
    FILE *f = fopen(argv[1], "rb");
    if (!f) { perror(argv[1]); return 1; }
    fseek(f, 0, SEEK_END);
    imglen = (size_t)ftell(f);
    fseek(f, 0, SEEK_SET);
    img = malloc(imglen);
    if (!img || fread(img, 1, imglen, f) != imglen) { fprintf(stderr, "jitgen: read failed\n"); return 1; }
    fclose(f);
    const Ehdr *eh = (const Ehdr *)(const void *)img;
    if (memcmp(eh->ident, "\177ELF", 4) != 0 || eh->ident[4] != 2 || (eh->machine != 62 && eh->machine != 183)) { fprintf(stderr, "jitgen: not an x86-64 / AArch64 ELF object\n"); return 1; }
    const int a64 = eh->machine == 183;
    const Shdr *sh = (const Shdr *)(const void *)(img + eh->shoff);
    const char *shstr = (const char *)img + sh[eh->shstrndx].offset;

    /* pass 1: names. With a master header (the x86-64 stencils.h) the stencil list is the master's, in its order: a stencil the object
     * does not define is emitted empty (length 0: the JIT refuses a region that needs it). */
    int ns = 0;
    static int sec_of[2048];
    static char mnames[2048][64];
    if (argc == 3) {
        FILE *mf = fopen(argv[2], "r");
        char line[256];
        if (!mf) { perror(argv[2]); return 1; }
        int in_enum = 0;
        while (fgets(line, sizeof line, mf)) {
            if (strncmp(line, "enum {", 6) == 0 && !in_enum && ns == 0) { in_enum = 1; continue; }
            if (in_enum) {
                char nm[64];
                if (sscanf(line, " ST_%63[A-Za-z0-9_],", nm) == 1 && strcmp(nm, "COUNT") != 0) { snprintf(mnames[ns], sizeof mnames[ns], "%s", nm); sec_of[ns++] = -1; }
                if (strstr(line, "ST_COUNT")) break;
            }
        }
        fclose(mf);
        for (int i = 0; i < eh->shnum; i++) {
            const char *n = shstr + sh[i].name;
            if (strncmp(n, ".text.", 6) != 0 || sh[i].type != 1) continue;
            int found = 0;
            for (int k = 0; k < ns; k++) if (strcmp(mnames[k], n + 6) == 0) { sec_of[k] = i; found = 1; break; }
            if (!found) {   /* a stencil only this target has: appended after the master's list */
                if (ns >= 2000) { fprintf(stderr, "jitgen: too many stencils\n"); return 1; }
                snprintf(mnames[ns], sizeof mnames[ns], "%s", n + 6);
                sec_of[ns++] = i;
            }
        }
    } else {
        for (int i = 0; i < eh->shnum; i++) {
            const char *n = shstr + sh[i].name;
            if (strncmp(n, ".text.", 6) == 0 && sh[i].type == 1) { snprintf(mnames[ns], sizeof mnames[ns], "%s", n + 6); sec_of[ns++] = i; }
        }
    }
    printf("/* generated by tools/jitgen.c from stencils.S -- do not edit; run `make jit-regen` */\n");
    printf("enum {\n");
    for (int k = 0; k < ns; k++) printf("    ST_%s,\n", mnames[k]);
    printf("    ST_COUNT\n};\n");
    printf("enum { HOLE_H0, HOLE_H1, HOLE_H2, HOLE_H3, HOLE_H4, HOLE_H5, HOLE_HQ, HOLE_T, HOLE_X, HOLE_HQ2, HOLE_B0, HOLE_B1, HOLE_B2, HOLE_B3, HOLE_B4, HOLE_B5 };\n");
    printf("enum { REL_ABS8, REL_ABS32, REL_ABS64, REL_PC32, REL_A64_ADD12, REL_A64_LD8, REL_A64_LD16, REL_A64_LD32, REL_A64_LD64, REL_A64_MOVW0, REL_A64_MOVW1, REL_A64_MOVW2, REL_A64_MOVW3, REL_A64_JUMP26, REL_A64_COND19, REL_A64_TST14 };\n");
    printf("typedef struct { uint16_t at; uint8_t hole, kind; int32_t addend; } JReloc;\n");
    printf("typedef struct { uint32_t off, len, rel0, nrel; } JStencil;\n");

    /* bytes + relocs */
    size_t total = 0;
    int nrel_total = 0;
    printf("static const unsigned char jst_code[] = {");
    for (int k = 0; k < ns; k++) {
        if (sec_of[k] < 0) continue;
        const Shdr *s = &sh[sec_of[k]];
        for (uint64_t b = 0; b < s->size; b++) {
            if (total % 16 == 0) printf("\n    ");
            printf("0x%02x,", img[s->offset + b]);
            total++;
        }
    }
    printf("\n};\n");
    printf("static const JReloc jst_rel[] = {\n");
    static uint32_t off[2048], len[2048], rel0[2048], nrel[2048];
    size_t o = 0;
    for (int k = 0; k < ns; k++) {
        off[k] = (uint32_t)o;
        rel0[k] = (uint32_t)nrel_total;
        if (sec_of[k] < 0) { len[k] = 0; continue; }
        const Shdr *s = &sh[sec_of[k]];
        len[k] = (uint32_t)s->size;
        o += s->size;
        for (int j = 0; j < eh->shnum; j++) {
            if (sh[j].type != 4 || sh[j].info != (uint32_t)sec_of[k]) continue;
            const Sym *syms = (const Sym *)(const void *)(img + sh[sh[j].link].offset);
            const char *strs = (const char *)img + sh[sh[sh[j].link].link].offset;
            const Rela *r = (const Rela *)(const void *)(img + sh[j].offset);
            size_t nr = sh[j].size / sizeof(Rela);
            for (size_t q = 0; q < nr; q++) {
                uint32_t type = (uint32_t)(r[q].info & 0xffffffffu), sym = (uint32_t)(r[q].info >> 32);
                int hole = hole_id(strs + syms[sym].name);
                const char *kind;
                if (!a64) {
                    if (type == 14) kind = "REL_ABS8";                      /* R_X86_64_8 */
                    else if (type == 10 || type == 11) kind = "REL_ABS32"; /* R_X86_64_32 / 32S */
                    else if (type == 1) kind = "REL_ABS64";                /* R_X86_64_64 */
                    else if (type == 2 || type == 4) kind = "REL_PC32";    /* PC32 / PLT32 */
                    else { fprintf(stderr, "jitgen: unsupported relocation type %u\n", type); return 1; }
                } else {
                    switch (type) {
                    case 257: kind = "REL_ABS64"; break;                    /* R_AARCH64_ABS64 */
                    case 258: kind = "REL_ABS32"; break;                    /* R_AARCH64_ABS32 */
                    case 277: kind = "REL_A64_ADD12"; break;                /* ADD_ABS_LO12_NC */
                    case 278: kind = "REL_A64_LD8"; break;                  /* LDST8_ABS_LO12_NC */
                    case 284: kind = "REL_A64_LD16"; break;
                    case 285: kind = "REL_A64_LD32"; break;
                    case 286: kind = "REL_A64_LD64"; break;
                    case 263: case 264: kind = "REL_A64_MOVW0"; break;      /* MOVW_UABS_G0(_NC) */
                    case 265: case 266: kind = "REL_A64_MOVW1"; break;
                    case 267: case 268: kind = "REL_A64_MOVW2"; break;
                    case 269: kind = "REL_A64_MOVW3"; break;
                    case 282: case 283: kind = "REL_A64_JUMP26"; break;     /* JUMP26 / CALL26 */
                    case 280: kind = "REL_A64_COND19"; break;               /* CONDBR19 */
                    case 279: kind = "REL_A64_TST14"; break;                /* TSTBR14 */
                    default: fprintf(stderr, "jitgen: unsupported AArch64 relocation type %u\n", type); return 1;
                    }
                }
                printf("    {%u, HOLE_%s, %s, %d},\n", (unsigned)r[q].offset,
                       hole <= 5 ? hole_names[hole] : hole == 6 ? "HQ" : hole == 7 ? "T" :
                       hole == 8 ? "X" : hole == 9 ? "HQ2" : hole_names[hole] + 1,
                       kind, (int)r[q].addend);
                nrel_total++;
                nrel[k]++;
            }
        }
    }
    printf("    {0, 0, 0, 0}\n};\n");
    printf("static const JStencil jst_tab[ST_COUNT] = {\n");
    for (int k = 0; k < ns; k++) printf("    {%u, %u, %u, %u}, /* %s */\n", off[k], len[k], rel0[k], nrel[k], mnames[k]);
    printf("};\n");
    free(img);
    return 0;
}
